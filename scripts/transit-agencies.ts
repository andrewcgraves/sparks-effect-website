// Writes src/legal/transitAgencies.ts, the agencies the attribution page
// credits, from the serving generation's gtfs-manifest.csv. Rerun it whenever
// `make cycle-tiles` moves production to a new generation:
//
//   kubectl -n sparks-effect exec deploy/valhalla -c valhalla -- \
//     cat /custom_files/<generation>/gtfs-manifest.csv > gtfs-manifest.csv
//   make transit-agencies MANIFEST=gtfs-manifest.csv GENERATION=<generation>
//
// The manifest does not record which generation it belongs to, so that is the
// second argument.

import { readFileSync, writeFileSync } from 'node:fs'
import { agenciesFromManifest } from '../src/legal/manifestAgencies.ts'

const OUT = new URL('../src/legal/transitAgencies.ts', import.meta.url)
const GENERATION_ID = /^gen-\d{8}T\d{6}Z-[0-9a-f]+$/

// Single-quoted, like the rest of the source.
function literal(text: string): string {
  return `'${text.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`
}

const [manifestPath, generation] = process.argv.slice(2)
if (!manifestPath || !generation || !GENERATION_ID.test(generation)) {
  console.error('usage: make transit-agencies MANIFEST=<gtfs-manifest.csv> GENERATION=<gen-YYYYMMDDTHHMMSSZ-hash>')
  process.exit(1)
}

const { agencies, manifestDate } = agenciesFromManifest(readFileSync(manifestPath, 'utf8'))
if (agencies.length === 0 || !manifestDate) {
  console.error(`${manifestPath} has no fetched or cached feeds to credit`)
  process.exit(1)
}

const lines = [
  `// Generated by scripts/transit-agencies.ts from ${generation}'s gtfs-manifest.csv.`,
  '// Do not edit by hand: rerun `make transit-agencies` instead.',
  '',
  "import type { TransitAgency } from './manifestAgencies'",
  '',
  `export const GENERATION = ${literal(generation)}`,
  '',
  `export const MANIFEST_DATE = ${literal(manifestDate)}`,
  '',
  'export const TRANSIT_AGENCIES: TransitAgency[] = [',
  ...agencies.map(({ name, href }) => `  { name: ${literal(name)}, href: ${literal(href)} },`),
  ']',
  '',
]
writeFileSync(OUT, lines.join('\n'))
console.log(`wrote ${agencies.length} agencies from ${generation} (fetched ${manifestDate})`)
